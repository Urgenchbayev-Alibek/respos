namespace Restaurant.Infrastructure.Persistence.Configurations;

internal sealed class RolePermissionConfiguration : IEntityTypeConfiguration<RolePermission>
{
    public void Configure(EntityTypeBuilder<RolePermission> builder)
    {
        builder.ToTable("role_permissions");
        builder.HasKey(e => new { e.RoleId, e.PermissionCode });
        builder.Property(e => e.PermissionCode).HasMaxLength(CodeLength);
        builder.HasOne(e => e.Permission).WithMany()
            .HasForeignKey(e => e.PermissionCode).HasPrincipalKey(p => p.Code)
            .OnDelete(DeleteBehavior.Cascade);
    }
}
